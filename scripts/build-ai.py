"""Regenerate position-independent x86 AI bytes (GCC/binutils; no runtime imports)."""
import argparse, hashlib, pathlib, subprocess
root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--tool-dir', required=True)
parser.add_argument('--module', choices=['run','traffic','impact','opponents','knockdown','rank'], default='run')
args = parser.parse_args()
name, target = {'rank':('RankBatch','LauncherRankNative.cs'), 'knockdown':('Knockdown','LauncherKnockdownNative.cs'), 'opponents':('OpponentRules','LauncherOpponentNative.cs'), 'traffic':('TrafficDrive','LauncherTrafficNative.cs'),
                'run':('LongRunAi','LauncherAiNative.cs'),
                'impact':('ImpactAudio','LauncherImpactAudioNative.cs')}[args.module]
bin = pathlib.Path(args.tool_dir)
out = root / 'artifacts' / 'ai-native'
out.mkdir(parents=True, exist_ok=True)
src = root / 'src' / (name+'.c')
obj = out / (name+'.o')
asm = out / (name+'.s')
subprocess.run([str(bin/'gcc.exe'), '-m32', '-Os', '-ffreestanding', '-fno-stack-protector',
    '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fno-ident', '-fno-jump-tables',
    '-fno-tree-switch-conversion', '-Wall', '-Wextra', '-Werror', '-S', str(src), '-o', str(asm)], check=True)
# Some x64-only binutils builds lack pe-bigobj-i386. The COFF container can be
# x64 while .code32 explicitly encodes every instruction for the x86 runtime.
asm.write_text('.code32\n'+asm.read_text(), encoding='utf-8')
subprocess.run([str(bin/'as.exe'), '--64', str(asm), '-o', str(obj)], check=True)
relocs = subprocess.check_output([str(bin/'objdump.exe'), '-r', str(obj)], text=True)
assert 'RELOCATION RECORDS' not in relocs, 'Code must have no relocations'
sections = subprocess.check_output([str(bin/'objdump.exe'), '-h', str(obj)], text=True)
for line in sections.splitlines():
    fields=line.split()
    if len(fields)>2 and fields[0].isdigit() and int(fields[2],16):
        assert fields[1]=='.text', 'Unexpected non-code data: '+line
raw = out/(name+'.bin')
subprocess.run([str(bin/'objcopy.exe'), '-O', 'binary', '--only-section=.text', str(obj), str(raw)], check=True)
text = raw.read_bytes()
code_limit = {'knockdown': 0x3000, 'rank': 0x1000 - 0x80}.get(args.module, 0x2000)
assert text and len(text) < code_limit, 'Code exceeds the allocated region'
symbols = subprocess.check_output([str(bin/'nm.exe'), str(obj)], text=True)
entry = '@PrepareOpponent@12' if args.module == 'opponents' else '@'+name+('@16' if args.module in ('traffic','knockdown') else '@8')
entry_offset, = [int(line.split()[0],16) for line in symbols.splitlines() if line.endswith(' T '+entry)]
assert args.module == 'rank' or entry_offset == 0, 'Entrypoint must start at zero'
assert ' U ' not in symbols, 'Unexpected runtime dependency'
digest = hashlib.sha256(src.read_bytes()).hexdigest()
lines = [', '.join('0x%02X'%n for n in text[i:i+16]) for i in range(0,len(text),16)]
generated = '// Generated by scripts/build-ai.py from '+name+'.c; do not hand edit.\n'
generated += 'internal static class '+name+'Native\n{\n    internal const string SourceSha256 = "'+digest+'";\n'
if args.module == 'rank':
    generated += '    internal const int EntryOffset = '+str(entry_offset)+';\n'
if args.module == 'opponents':
    offset, = [int(line.split()[0],16) for line in symbols.splitlines() if line.endswith(' T @OpponentTarget@16')]
    generated += '    internal const int TargetOffset = '+str(offset)+';\n'
generated += '    internal static readonly byte[] Code = {\n        '+',\n        '.join(lines)+'\n    };\n}\n'
(root/'src'/target).write_text(generated, encoding='utf-8')
print('Generated',len(text),'position-independent x86 bytes; source SHA256',digest)
